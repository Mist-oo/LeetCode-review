async page => {
  if(new URL(page.url()).origin!=='http://127.0.0.1:8766')throw new Error('Isolated QA on 8766 only');
  const assert=(value,message)=>{if(!value)throw new Error(message);};let checks=0;
  await page.setViewportSize({width:1440,height:1000});
  const base='http://127.0.0.1:8766',provider='http://127.0.0.1:8767';
  const errors=[];page.on('pageerror',error=>errors.push(String(error)));
  const stats=async()=>await (await page.request.get(provider+'/stats')).json();
  const mode=value=>page.request.post(provider+'/control',{data:{mode:value}});
  const enter=async()=>{
    await page.getByRole('searchbox',{name:'搜索题目',exact:true}).fill('两数之和');
    await page.getByRole('button',{name:'⤨ 随机复习',exact:true}).click();
    await page.locator('#review-source').waitFor();
  };
  const waitBadge=text=>page.waitForFunction(text=>document.querySelector('#review-source-status')?.textContent===text,text);
  const currentId=()=>page.evaluate(()=>reviewState?.variant?.id);
  await mode('success');const initial=await stats();
  await page.request.put(base+'/api/ai/settings',{data:{base_url:'',model:'',clear_key:true}});
  await page.evaluate(()=>localStorage.removeItem('leetcode-review-source'));
  await page.reload();await enter();
  assert(await page.locator('#review-source').inputValue()==='fixed','first use defaults fixed');checks++;
  await page.locator('#review-source').selectOption('ai');
  await page.waitForFunction(()=>document.querySelector('.error-banner')?.textContent.includes('配置'));
  assert((await currentId()).startsWith('fixed-'),'missing config falls back fixed');checks++;
  assert(!(await page.locator('#practice-title').innerText()).includes('两数之和'),'fallback does not reveal identity');checks++;
  await page.getByRole('button',{name:'服务设置',exact:true}).click();
  await page.locator('#ai-base-url').fill(provider+'/v1');
  await page.locator('#ai-model').fill('fake-browser-'+Date.now());
  await page.locator('#ai-api-key').fill('fake-local-test-key');
  await page.getByRole('button',{name:'保存到本机',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert((await stats()).calls===initial.calls,'saving configuration does not call model');checks++;
  const code=await page.locator('.CodeMirror').evaluate(el=>el.CodeMirror.getValue());
  await page.getByRole('button',{name:'换个说法',exact:true}).click();await waitBadge('AI 新生成');
  const first=await currentId();assert(first.startsWith('ai-'),'AI new variant');checks++;
  assert((await stats()).calls===initial.calls+2,'generation and review exactly twice');checks++;
  assert(await page.locator('#test-input').inputValue()==='3\n4 6 9\n10\n3\n8 -3 2\n5\n','AI sample sync');checks++;
  await page.screenshot({path:'output/playwright/v3-ai-review.png',fullPage:false});
  await page.getByRole('button',{name:'← 记录矩阵',exact:true}).click();await enter();await waitBadge('AI 缓存');
  assert(await currentId()===first&&(await stats()).calls===initial.calls+2,'reopen uses cache without requests');checks++;
  await page.reload();await enter();await waitBadge('AI 缓存');
  assert(await page.locator('#review-source').inputValue()==='ai','source preference survives reload');checks++;
  await page.getByRole('button',{name:'换个说法',exact:true}).click();await waitBadge('AI 新生成');
  const second=await currentId();assert(second!==first&&(await stats()).calls===initial.calls+4,'force creates checked new version');checks++;
  await mode('fail-review');await page.getByRole('button',{name:'换个说法',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.error-banner')?.textContent.includes('一致性'));
  assert((await currentId()).startsWith('fixed-'),'semantic rejection visibly falls back');checks++;
  assert((await stats()).calls===initial.calls+6,'failed review not retried');checks++;
  await page.reload();await enter();await waitBadge('AI 缓存');
  assert(await currentId()===second,'failed generation keeps old valid cache');checks++;
  await mode('http-error');await page.getByRole('button',{name:'换个说法',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.error-banner')?.textContent.includes('HTTP 503'));
  assert((await currentId()).startsWith('fixed-'),'network/provider failure fixed fallback');checks++;
  await page.reload();await enter();await waitBadge('AI 缓存');
  assert(await currentId()===second&&(await stats()).calls===initial.calls+7,'cache works without provider access');checks++;
  await page.locator('#review-source').selectOption('fixed');
  assert((await currentId()).startsWith('fixed-'),'manual fixed source works');checks++;
  await mode('slow');await page.locator('#review-source').selectOption('ai');await waitBadge('AI 缓存');
  const pending=page.waitForResponse(response=>response.url().endsWith('/api/problems/1/ai-variant'));
  await page.getByRole('button',{name:'换个说法',exact:true}).click();
  assert(await page.getByRole('button',{name:'换个说法',exact:true}).isDisabled(),'generation action disabled while pending');checks++;
  await page.locator('#review-source').selectOption('fixed');await pending;
  assert(await page.locator('#review-source').inputValue()==='fixed'&&(await currentId()).startsWith('fixed-'),'late result does not override selected source');checks++;
  await page.locator('#review-source').selectOption('ai');await waitBadge('AI 缓存');
  assert((await stats()).calls===initial.calls+9,'late successful result persisted and then reused');checks++;
  assert(await page.locator('.CodeMirror').evaluate(el=>el.CodeMirror.getValue())===code,'code unaffected');checks++;
  assert(errors.length===0,'no uncaught app exceptions');checks++;
  const wrongVersion=await page.evaluate(()=>({...reviewState.variant,contract_version:'wrong-contract'}));
  await page.route('**/api/problems/1/ai-variant',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(wrongVersion)}));
  await page.getByRole('button',{name:'换个说法',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.error-banner')?.textContent.includes('版本不一致'));
  assert((await currentId()).startsWith('fixed-'),'mismatched contract cannot be displayed');checks++;
  await page.unroute('**/api/problems/1/ai-variant');
  await page.request.put(base+'/api/ai/settings',{data:{base_url:'',model:'',clear_key:true}});
  await page.reload();await enter();
  await page.waitForFunction(()=>document.querySelector('.error-banner')?.textContent.includes('配置'));
  assert((await currentId()).startsWith('fixed-'),'cleared config uses fixed even with old cache');checks++;
  await page.locator('#review-source').selectOption('fixed');await mode('success');
  return {checks,passed:true,provider:'loopback fixture; no external paid model used'};
}
